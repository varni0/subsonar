import java.util.Locale

/** What a subscription shows in its avatar: one of our own line icons, or an emoji the user picked. No brand logos. */
sealed interface Avatar {
    data class Icon(val key: String) : Avatar
    data class Emoji(val emoji: String) : Avatar
}

/** Resolved look of one subscription (after applying the smart defaults). */
data class Visual(val avatar: Avatar, val colorKey: String, val isAutomatic: Boolean)

/**
 * Per-subscription colour + icon/emoji. Stored on [Subscription.colorKey] / [Subscription.avatar] (null = automatic).
 * Keys are stable strings (never indexes), so the palette and icon set can be reordered or extended safely.
