    /** Smart default icon: name keywords first (e.g. "Fitnessclub" -> gym), then the category. */
    fun defaultIcon(name: String, category: Category): String {
        val normalized = name.lowercase(Locale.ROOT)
        val words = normalized.split(Regex("[^\\p{L}\\p{N}+]+")).filter { it.isNotEmpty() }.toSet()
        for ((icon, keys) in KEYWORDS) {
            for (k in keys) {
                val hit = if (k.length >= 5 || ' ' in k) normalized.contains(k) else k in words
                if (hit) return icon
            }
        }
        return categoryIcon(category)
    }

    fun resolve(name: String, category: Category, colorKey: String?, avatar: String?): Visual {
        val chosenAvatar = parse(avatar)
        val chosenColor = validColor(colorKey)
        return Visual(
            avatar = chosenAvatar ?: Avatar.Icon(defaultIcon(name, category)),
            colorKey = chosenColor ?: defaultColor(category),
            isAutomatic = chosenAvatar == null && chosenColor == null,
        )
    }

    fun resolve(sub: Subscription): Visual = resolve(sub.name, sub.category, sub.colorKey, sub.avatar)
}
