    private const val ICON_PREFIX = "icon:"
    private const val EMOJI_PREFIX = "emoji:"
    private const val MAX_EMOJI_LENGTH = 16

    fun encode(avatar: Avatar): String = when (avatar) {
        is Avatar.Icon -> ICON_PREFIX + avatar.key
        is Avatar.Emoji -> EMOJI_PREFIX + avatar.emoji
    }

    /** Parses a stored avatar; unknown icons or garbage give null (= automatic), never a crash. */
    fun parse(stored: String?): Avatar? = when {
        stored == null -> null
        stored.startsWith(ICON_PREFIX) -> stored.removePrefix(ICON_PREFIX).takeIf { it in ICONS }?.let(Avatar::Icon)
        stored.startsWith(EMOJI_PREFIX) -> stored.removePrefix(EMOJI_PREFIX).trim()
            .takeIf { it.isNotEmpty() && it.length <= MAX_EMOJI_LENGTH }?.let(Avatar::Emoji)
        else -> null
    }

    fun validColor(key: String?): String? = key?.takeIf { it in COLORS }

    fun defaultColor(category: Category): String = when (category) {
        Category.STREAMING -> "lingonberry"
        Category.MUSIC -> "heather"
        Category.SOFTWARE -> "dusk"
        Category.CLOUD -> "lake"
