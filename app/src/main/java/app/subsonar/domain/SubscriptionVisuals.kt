        Category.NEWS -> "slate"
        Category.FITNESS -> "rust"
        Category.UTILITIES -> "cloudberry"
        Category.PHONE_INTERNET -> "fjord"
        Category.INSURANCE -> "pine"
        Category.EDUCATION -> "moss"
        Category.OTHER -> "birch"
